/**
 * 수식 편집 창의 자동완성이 쓰는 LaTeX 명령 목록(KaTeX가 그릴 수 있는 것만).
 * 명령마다 **설명(`desc`)**, 그려 보일 **예시(`example`)**, 고르면 들어갈 **삽입 글자(`insert`)**를 갖는다.
 * `insert`의 `$0`은 고른 뒤 커서가 놓일 자리다(없으면 끝). `keys`는 이름 말고 찾을 수 있는 낱말(한글·영어, 공백으로 구분).
 */
export interface LatexCommand {
  /** 역슬래시 없는 이름(예: `frac`). */
  name: string;
  /** 분류 이름(목록 옆에 작게 보인다). */
  kind: string;
  /** 한 줄 설명. */
  desc: string;
  /** 고르면 들어갈 글자. `$0`은 커서 자리. */
  insert: string;
  /** 설명 옆에 그려 보일 LaTeX. */
  example: string;
  /** 이름 말고도 찾을 수 있는 낱말들(소문자 기준, 공백 구분). */
  keys: string;
}

